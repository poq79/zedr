// composeUserGuidance 把定向/通用解释拼到 Summary 尾部。
// 单独成段（【给你的说明】）便于前端把它渲染成独立区块，也便于用户扫读。
func composeUserGuidance(res *Result) string {
	if res == nil || res.Verdict == model.VerdictSafe {
		return "" // 无害判定不需要解释，避免打扰
	}

	var means, act string
	for _, id := range res.RuleIDs {
		if g, ok := ruleGuidance[id]; ok {
			means, act = g[0], g[1]
			break
		}
	}
	// 信号层也可能有定向解释（DROP-001 / P-001 优先级高于规则）
	for _, s := range res.Evidence.Signals {
		if g, ok := ruleGuidance[s.ID]; ok {
			means, act = g[0], g[1]
			break
		}
	}
	if means == "" {
		// 通用模板：按判定分级给出克制的解释——不渲染恐慌，也不过度安抚
		switch res.Verdict {
		case model.VerdictMalicious:
			means = "这个进程的行为组合达到了恶意判定线，建议按恶意样本处理。"
			act = "在管理台查看完整证据链后处置；不确定时先隔离等管理员确认。"
		default:
			means = "这个进程有一些值得注意的行为，但单独还不足以判定恶意。"
			act = "留观即可；反复出现时让管理员看一眼证据链。"
		}
	}

	var b strings.Builder
	b.WriteString("\n\n【给你的说明】")
	fmt.Fprintf(&b, "发生了什么：%s\n", firstLine(res.Title))
	fmt.Fprintf(&b, "通常意味着：%s\n", means)
	fmt.Fprintf(&b, "建议你：%s", act)
	return b.String()
}

// firstLine 取标题主体，去掉可能存在的尾部细节。
func firstLine(s string) string {
	if i := strings.IndexAny(s, "（("); i > 0 {
		return strings.TrimSpace(s[:i])
	}
	return s
}
