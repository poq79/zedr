// 用户可读的告警解释。
//
// 为什么需要这一层：安全团队看到「HG-021 未签名程序以管理员权限从可写目录
// 运行」知道该干什么，但被装机器的普通用户只会慌或无视。把"发生了什么 /
// 通常意味着什么 / 建议怎么做"用大白话拼进告警 Summary，桌面端与管理台
// 零前端改动即可呈现——解释是告警的一部分，不是另一个系统的事。

